/**
 * Example: Design System Starter — CSS custom properties generator
 *
 * Demonstrates the color system and typography patterns from the
 * frontend-design-pro skill. Run this file to generate a CSS custom
 * properties snippet for a new project.
 *
 * Usage:
 *   node scripts/generate-design-tokens.mjs --hue 38 --mode dark
 *
 * Options:
 *   --hue <0-360>    Base hue for the palette (default: 38)
 *   --mode <dark|light>  Color mode (default: dark)
 *   --name <string>  Project name for the generated comment header
 */

const args = process.argv.slice(2);
function getArg(flag, fallback) {
  const idx = args.indexOf(flag);
  return idx >= 0 ? args[idx + 1] : fallback;
}

const HUE = parseInt(getArg('--hue', '38'), 10);
const MODE = getArg('--mode', 'dark');
const NAME = getArg('--name', 'Project');

function hsl(h, s, l) {
  return `hsl(${h}, ${s}%, ${l}%)`;
}

// ── Generate Neutral Scale ──────────────────────────
// Low saturation (5%), varying lightness
function neutralTokens(mode) {
  if (mode === 'dark') {
    return {
      '--color-bg':                hsl(HUE, 5, 4),
      '--color-bg-elevated':       hsl(HUE, 5, 7),
      '--color-surface':           hsl(HUE, 5, 10),
      '--color-surface-elevated':  hsl(HUE, 5, 14),
      '--color-border':            hsl(HUE, 5, 18),
      '--color-border-hover':      hsl(HUE, 5, 26),
      '--color-text-dim':          hsl(HUE, 5, 35),
      '--color-text-muted':        hsl(HUE, 5, 50),
      '--color-text':              hsl(HUE, 10, 88),
      '--color-text-bright':       hsl(HUE, 10, 94),
    };
  }
  return {
    '--color-bg':                hsl(HUE, 5, 96),
    '--color-bg-elevated':       hsl(HUE, 5, 92),
    '--color-surface':           hsl(HUE, 5, 100),
    '--color-surface-elevated':  hsl(HUE, 5, 98),
    '--color-border':            hsl(HUE, 5, 85),
    '--color-border-hover':      hsl(HUE, 5, 75),
    '--color-text-dim':          hsl(HUE, 5, 65),
    '--color-text-muted':        hsl(HUE, 5, 45),
    '--color-text':              hsl(HUE, 10, 12),
    '--color-text-bright':       hsl(HUE, 10, 6),
  };
}

// ── Generate Accent Scale ────────────────────────────
function accentTokens(hue) {
  return {
    '--color-accent-darkest': hsl(hue, 80, 20),
    '--color-accent-dark':    hsl(hue, 70, 35),
    '--color-accent':         hsl(hue, 65, 50),
    '--color-accent-light':   hsl(hue, 60, 65),
    '--color-accent-lightest':hsl(hue, 40, 88),
  };
}

// ── Generate Semantic States ─────────────────────────
const semanticTokens = {
  '--color-success': 'hsl(140, 55%, 50%)',
  '--color-success-bg': 'hsla(140, 55%, 50%, 0.12)',
  '--color-warning': 'hsl(38, 75%, 52%)',
  '--color-warning-bg': 'hsla(38, 75%, 52%, 0.12)',
  '--color-error': 'hsl(0, 65%, 55%)',
  '--color-error-bg': 'hsla(0, 65%, 55%, 0.12)',
};

// ── Generate Spacing Scale ───────────────────────────
const spacingTokens = {
  '--space-xs': '4px',
  '--space-sm': '8px',
  '--space-md': '16px',
  '--space-lg': '24px',
  '--space-xl': '32px',
  '--space-2xl': '48px',
  '--space-3xl': '64px',
  '--space-4xl': '96px',
};

// ── Generate Typography Tokens ───────────────────────
const typographyTokens = {
  '--font-display': '"Cormorant Garamond", Georgia, "Times New Roman", serif',
  '--font-body': '"JetBrains Mono", "Fira Code", "Courier New", monospace',
  '--font-size-xs': 'clamp(0.7rem, 0.65rem + 0.2vw, 0.75rem)',
  '--font-size-sm': 'clamp(0.8rem, 0.75rem + 0.2vw, 0.875rem)',
  '--font-size-base': 'clamp(0.95rem, 0.9rem + 0.3vw, 1.0625rem)',
  '--font-size-lg': 'clamp(1.1rem, 1rem + 0.5vw, 1.25rem)',
  '--font-size-xl': 'clamp(1.4rem, 1.2rem + 1vw, 1.75rem)',
  '--font-size-2xl': 'clamp(1.8rem, 1.4rem + 1.8vw, 2.5rem)',
  '--font-size-3xl': 'clamp(2.2rem, 1.6rem + 3vw, 3.5rem)',
  '--font-size-4xl': 'clamp(2.8rem, 1.8rem + 5vw, 5rem)',
  '--leading-tight': '1.1',
  '--leading-base': '1.6',
  '--leading-relaxed': '1.8',
};

// ── Generate Radius & Shadow Tokens ──────────────────
const miscTokens = {
  '--radius-sm': '2px',
  '--radius-md': '4px',
  '--radius-lg': '8px',
  '--radius-full': '9999px',
  '--shadow-sm': '0 1px 2px rgba(0,0,0,0.3)',
  '--shadow-md': '0 2px 8px rgba(0,0,0,0.4)',
  '--shadow-lg': '0 4px 16px rgba(0,0,0,0.5)',
};

// ── Assemble and Output ──────────────────────────────
const tokens = {
  ...neutralTokens(MODE),
  ...accentTokens(HUE),
  ...semanticTokens,
  ...spacingTokens,
  ...typographyTokens,
  ...miscTokens,
};

console.log(`/* ═══════════════════════════════════════════════════════
   Design Tokens — ${NAME}
   Generated by frontend-design-pro
   Hue: ${HUE}°  |  Mode: ${MODE}
   ═══════════════════════════════════════════════════════ */

:root {`);

let maxLen = 0;
for (const k of Object.keys(tokens)) maxLen = Math.max(maxLen, k.length);

for (const [key, value] of Object.entries(tokens)) {
  const pad = ' '.repeat(maxLen - key.length + 2);
  console.log(`  ${key}:${pad}${value};`);
}

console.log('}');
console.log('\n@media (prefers-color-scheme: ' +
  (MODE === 'dark' ? 'light' : 'dark') + ') {');
console.log('  :root {');
console.log('    /* Define opposite-mode tokens here */');
console.log('  }');
console.log('}');

// ── Print WCAG contrast guidance ────────────────────
console.log('\n/* ── WCAG Contrast Notes ────────────────────────────');
if (MODE === 'dark') {
  console.log('   Body text: ensure --color-text vs --color-bg >= 4.5:1');
  console.log('   Large text: ensure --color-text vs --color-bg >= 3:1');
  console.log('   Verify at: https://colourcontrast.cc');
} else {
  console.log('   Body text: ensure --color-text vs --color-bg >= 4.5:1');
  console.log('   Large text: ensure --color-text vs --color-bg >= 3:1');
  console.log('   Verify at: https://colourcontrast.cc');
}
console.log('   ─────────────────────────────────────────────────── */');
